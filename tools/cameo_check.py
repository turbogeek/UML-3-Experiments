REPO_SCRIPTS = ROOT / "tools" / "cameo-scripts"
CUSTOMIZATION = ROOT / "customization" / "catia-magic"
PALETTE_EXPECTED = ROOT / "tests" / "cameo" / "palette-expectations.json"
HYPOTHESES = ROOT / "tests" / "cameo" / "implied-specializations.json"
# SCRIPTS_DIR hard-coded in start-v2language-test-harness.groovy
HARNESS_SCRIPTS = Path(os.environ.get("USERPROFILE", str(Path.home()))) / "Documents" / "GitHub" / "sysmlv2-validator" / "utilityScripts"


def sync_scripts(hypotheses: Path = HYPOTHESES) -> None:
    """Repo is the source of truth: pre-flight check the Groovy scripts, copy them and the
    hypotheses (as '|' lines - MagicDraw's GroovyShell has no groovy.json) to the harness dir."""
    scripts = sorted(REPO_SCRIPTS.glob("*.groovy"))
    r = subprocess.run(["groovy", str(ROOT / "tools" / "check_groovy.groovy"), *map(str, scripts)],
                       capture_output=True, text=True, shell=(os.name == "nt"))
    if r.returncode != 0:
        raise RuntimeError("Groovy pre-flight check failed:\n" + r.stdout + r.stderr)
    HARNESS_SCRIPTS.mkdir(parents=True, exist_ok=True)
    for s in scripts:
        shutil.copy2(s, HARNESS_SCRIPTS / s.name)
    cases = json.loads(hypotheses.read_text(encoding="utf-8"))
    lines = ["# generated by tools/cameo_check.py from tests/cameo/implied-specializations.json"]
    for c in cases["specializes"]:
        lines.append("|".join([c["id"], "specializes", "::".join(c["subject"]), "::".join(c["general"]),
                               str(c["expected"]).lower()]))
    for c in cases["inheritsFeature"]:
        lines.append("|".join([c["id"], "inheritsFeature", "::".join(c["subject"]), c["feature"],
                               str(c["expected"]).lower()]))
    (HARNESS_SCRIPTS / "uml3-implied-specializations.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_verify(text: str) -> tuple[list[dict], bool]:
    results, ok = [], True
    if not text or text.startswith("ERROR|"):
        return [{"error": text or "empty result"}], False
    for ln in text.splitlines():
        p = ln.split("|")
        if p[0] == "RESULT" and len(p) >= 6:
            results.append({"id": p[1], "status": p[2], "expected": p[3], "observed": p[4], "detail": p[5]})
            ok = ok and p[2] == "PASS"
    return results, ok and bool(results)


def call(port: int, path: str, payload: dict | None = None, timeout: int = 600) -> tuple[int, dict]:
    url = f"http://localhost:{port}{path}"
    data = None if payload is None else json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, method="GET" if payload is None else "POST",
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8", errors="replace")
            status = resp.status
    except urllib.error.HTTPError as e:  # harness uses 400/500 for model errors
        body = e.read().decode("utf-8", errors="replace")
        status = e.code
    try:
        return status, json.loads(body)
    except json.JSONDecodeError:
        return status, {"raw": body}


def split_errors(resp: dict) -> list[str]:
    err = resp.get("error") or ""
    # the harness joins diagnostics with a literal backslash-n
    return [ln for ln in err.replace("\\n", "\n").splitlines() if ln.strip()]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8770)
    ap.add_argument("--undo", action="store_true")
    ap.add_argument("--shutdown", action="store_true")
    ap.add_argument("--probes", nargs="*", default=[],
                    help="negative/exploratory probe files (EXPECT-CAMEO header), loaded after the library")
    ap.add_argument("--library-only", action="store_true", help="load only library/ (no examples)")
    ap.add_argument("--validate", action="store_true",
                    help="run CATIA Magic's KerML/SysML validation engine on loaded packages and compare "
                         "with tests/cameo-negative/validation-predictions.json")
    ap.add_argument("--idl", action="store_true",
                    help="IDL round trip in CATIA Magic for each tests/idl/*.idl (import, export, compare)")
    ap.add_argument("--views", action="store_true",
                    help="check view contents against tests/cameo/view-predictions.json (needs examples loaded)")
    ap.add_argument("--svg", action="store_true",
                    help="open each view of tests/cameo/svg-expectations.json as a diagram, lay it out, export SVG and "
                         "check display mode, overlaps, drawn shapes and SVG labels (needs examples; IDL views need --idl)")
    ap.add_argument("--palettes", action="store_true",
                    help="load customization/catia-magic and check the UML3 palettes CATIA Magic builds "
                         "(tests/cameo/palette-expectations.json)")
    ap.add_argument("--display", action="store_true",
                    help="check keyword labels against tests/cameo/display-expectations.json (needs examples loaded)")
    ap.add_argument("--hypotheses", help="hypotheses JSON to verify (default tests/cameo/implied-specializations.json)")
    ap.add_argument("files", nargs="*")
    args = ap.parse_args()
    LOGS.mkdir(parents=True, exist_ok=True)

    try:
        status, st = call(args.port, "/status", timeout=10)
    except Exception as exc:
        print(f"HARNESS UNAVAILABLE on port {args.port}: {exc!r} - start the SysMLv2 test harness in Cameo",
              file=sys.stderr)
        return 2
    if status != 200:
        print(f"HARNESS UNAVAILABLE: /status returned {status} {st}", file=sys.stderr)
        return 2

    if args.files:
        files = [Path(f).resolve() for f in args.files]
    else:
        files = [ROOT / "library" / f"{n}.sysml" for n in LIBRARY_ORDER]
        if not args.library_only:
            files += sorted((ROOT / "examples").glob("*.sysml"))
        if args.palettes:
            # the CATIA Magic customization builds on the libraries and the examples it draws
            files += [CUSTOMIZATION / "UML3CatiaMagic.sysml", CUSTOMIZATION / "examples" / "OnlineStoreCatiaMagicViews.sysml",
                      CUSTOMIZATION / "UML3CatiaMagicActivation.sysml"]
    missing = [str(f) for f in files if not f.exists()]
    if missing:
        print("MISSING FILES: " + ", ".join(missing), file=sys.stderr)
        return 2

    sync_scripts(Path(args.hypotheses).resolve() if args.hypotheses else HYPOTHESES)
    report: dict = {"started": dt.datetime.now().isoformat(timespec="seconds"), "port": args.port, "loads": []}
    _, before = call(args.port, "/run-script", {"scriptName": INSPECT_SCRIPT})
    report["inspectBefore"] = before.get("result", before)
    if "matches=0" not in str(report["inspectBefore"]):
        print("WARNING: UML3 packages already present in the project before loading:\n" + str(report["inspectBefore"]))

    failed = False
    for f in files:
        status, resp = call(args.port, "/load-sysml", {"filePath": f.as_posix()})
        errors = split_errors(resp)
        ok = status == 200 and resp.get("success") is True
        (LOGS / f"load-{f.stem}.json").write_text(json.dumps({"status": status, "response": resp}, indent=2),
                                                  encoding="utf-8")
        report["loads"].append({"file": str(f), "httpStatus": status, "success": ok, "errors": errors})
        print(f"{'PASS' if ok else 'FAIL'}  {f.name}  (HTTP {status}, {len(errors)} error lines)")
        for e in errors[:40]:
            print(f"    {e}")
        if not ok:
            failed = True
            print("    stopping: later files depend on this one")
            break

    _, after = call(args.port, "/run-script", {"scriptName": INSPECT_SCRIPT})
    report["inspectAfterLoads"] = after.get("result", after)

    # Negative probes: must be loaded after the library; each declares EXPECT-CAMEO: OK|ERROR
    if args.probes and not failed:
        probe_results = []
        for p in sorted(Path(x).resolve() for x in args.probes):
            text = p.read_text(encoding="utf-8")
            expected = "ERROR" if "EXPECT-CAMEO: ERROR" in text else ("OK" if "EXPECT-CAMEO: OK" in text else None)
            status, resp = call(args.port, "/load-sysml", {"filePath": p.as_posix()})
            observed = "OK" if status == 200 and resp.get("success") is True else "ERROR"
            errors = split_errors(resp)
            ok = expected is not None and observed == expected
            (LOGS / f"probe-{p.stem}.json").write_text(json.dumps({"status": status, "response": resp}, indent=2),
                                                        encoding="utf-8")
            probe_results.append({"file": p.name, "expected": expected, "observed": observed,
                                  "matchesPrediction": ok, "errors": errors})
            print(f"{'AS PREDICTED' if ok else 'SURPRISE    '}  {p.name}  expected {expected}, observed {observed}")
            for e in errors[:6]:
                print(f"    {e}")
        report["probes"] = probe_results

    # IDL round trip inside CATIA Magic: import (Groovy, one undoable session) -> export (read-only) -> compare
    #     with the canonical form of the original. Runs before validation so imported packages are validated too.
    if args.idl and not failed:
        core = (ROOT / "tools" / "idl" / "UML3IdlCore.groovy").as_posix()
        idl_logs = ROOT / "logs" / "idl"
        idl_logs.mkdir(parents=True, exist_ok=True)
        fixtures = sorted((ROOT / "tests" / "idl").glob("*.idl"))
        # packages the importer creates are named after the file; register them for the guarded undo
        # the importer also creates '<file>_views' (generated views of the imported file)
        (HARNESS_SCRIPTS / "uml3-undo-extra.txt").write_text(
            "\n".join(n for f in fixtures for n in (re.sub(r"[^A-Za-z0-9_]", "_", f.stem),
                                                  re.sub(r"[^A-Za-z0-9_]", "_", f.stem) + "_views")) + "\n",
            encoding="utf-8")
        rows = []
        for f in fixtures:
            pkg = re.sub(r"[^A-Za-z0-9_]", "_", f.stem)
            canonical = idl_logs / (f.stem + ".canonical.idl")
            subprocess.run(["groovy", str(ROOT / "tools" / "idl" / "idl2sysml.groovy"), str(f),
                            str(idl_logs / (f.stem + ".sysml")), str(canonical)], capture_output=True, text=True,
                           shell=(os.name == "nt"))
            (HARNESS_SCRIPTS / "uml3-idl-request.txt").write_text(
                f"idl={f.as_posix()}\ncore={core}\nsysmlOut={(idl_logs / ('cameo-' + f.stem + '.sysml')).as_posix()}\n",
                encoding="utf-8")
            _, imp = call(args.port, "/run-script", {"scriptName": "importIdl.groovy"})
            imp_text = imp.get("result") or imp.get("error") or ""
            exported = idl_logs / ("cameo-export-" + f.stem + ".idl")
            if exported.exists():
                exported.unlink()
            (HARNESS_SCRIPTS / "uml3-idl-export-request.txt").write_text(
                f"package={pkg}\ncore={core}\nidlOut={exported.as_posix()}\n", encoding="utf-8")
            _, exp = call(args.port, "/run-script", {"scriptName": "exportIdl.groovy"})
            exp_text = exp.get("result") or exp.get("error") or ""
            identical = exported.exists() and canonical.exists() and \
                exported.read_text(encoding="utf-8") == canonical.read_text(encoding="utf-8")
            row = {"file": f.name, "import": next((l for l in imp_text.splitlines() if l.startswith("RESULT|")), imp_text[:300]),
                   "export": next((l for l in exp_text.splitlines() if l.startswith("RESULT|")), exp_text[:300]),
                   "warnings": [l for l in (imp_text + "\n" + exp_text).splitlines() if l.startswith(("WARN|", "DIAG|ERROR"))],
                   "identical": identical}
            row["passed"] = row["import"].startswith("RESULT|OK") and row["export"].startswith("RESULT|OK") and identical
            rows.append(row)
            print(f"{'PASS' if row['passed'] else 'FAIL'}  IDL round trip {f.name}: import {row['import'][:60]} | "
                  f"export {row['export'][:40]} | identical={identical}")
        report["idlRoundTrip"] = {"passed": bool(rows) and all(r["passed"] for r in rows), "results": rows}
        failed = failed or not report["idlRoundTrip"]["passed"]

    # CATIA Magic validation engine on every loaded UML3*/OnlineStore* package
    if args.validate and not failed:
        _, val = call(args.port, "/run-script", {"scriptName": VALIDATE_SCRIPT})
        text = val.get("result") or val.get("error") or ""
        (LOGS / "validation-engine.txt").write_text(text, encoding="utf-8")
        # 'observed' is the regression expectation; a prediction not yet run falls back to its 'flagged' value
        expected = {p["package"]: p.get("observed", p["flagged"]) for p in
                    json.loads(VALIDATION_EXPECTED.read_text(encoding="utf-8"))["predictions"]}
        flagged: dict[str, bool] = {}
        rows = []
        for ln in text.splitlines():
            f = ln.split("|")
            if f[0] == "PKG" and len(f) >= 4:
                flagged.setdefault(f[1], False)
                if f[3].startswith("ERROR"):
                    rows.append({"package": f[1], "problem": "validation threw: " + f[3]})
            elif f[0] == "FAIL" and len(f) >= 6:
                if f[2].upper().startswith("ERR"):
                    flagged[f[1]] = True
                rows.append({"package": f[1], "severity": f[2], "rule": f[3], "element": f[4], "message": f[5]})
        mismatches = [f"{pkg}: expected flagged={expected.get(pkg)}, observed {obs}"
                      for pkg, obs in flagged.items() if pkg in expected and expected[pkg] != obs]
        unknown = [pkg for pkg in flagged if pkg not in expected]
        val_ok = bool(flagged) and not mismatches and not text.startswith("ERROR|") and \
            not any("problem" in r for r in rows)
        report["validationEngine"] = {"passed": val_ok, "packages": flagged, "failures": rows,
                                      "mismatches": mismatches, "packagesWithoutExpectation": unknown}
        print(f"{'PASS' if val_ok else 'FAIL'}  CATIA Magic validation engine "
              f"({len(flagged)} packages, {sum(flagged.values())} flagged as expected)" if val_ok else
              f"FAIL  CATIA Magic validation engine: {mismatches or text[:300]}")
        failed = failed or not val_ok

    # View contents (expose + filter) as CATIA Magic evaluates them
    if args.views and not failed:
        spec = json.loads(VIEW_EXPECTED.read_text(encoding="utf-8"))
        (HARNESS_SCRIPTS / "uml3-view-subjects.txt").write_text(
            "\n".join(v["view"] for v in spec["views"]) + "\n", encoding="utf-8")
        _, vr = call(args.port, "/run-script", {"scriptName": VIEW_SCRIPT})
        text = vr.get("result") or vr.get("error") or ""
        (LOGS / "view-contents.txt").write_text(text, encoding="utf-8")
        contents: dict[str, tuple[str, list[str]]] = {}
        for ln in text.splitlines():
            f = ln.split("|")
            if f[0] == "VIEW" and len(f) >= 6:
                contents[f[1]] = (f[3], [n for n in f[5].split(",") if n] if f[3] not in ("", "NONE") else [])
        results = []
        for v in spec["views"]:
            accessor, names = contents.get(v["view"], ("MISSING", []))
            missing = [n for n in v["includes"] if n not in names]
            unexpected = [n for n in v["excludes"] if n in names]
            ok = accessor not in ("MISSING", "NONE", "") and not missing and not unexpected
            results.append({"id": v["id"], "view": v["view"], "accessor": accessor, "count": len(names),
                            "missingIncludes": missing, "presentExcludes": unexpected, "passed": ok})
        views_ok = bool(results) and all(r["passed"] for r in results)
        report["viewContents"] = {"passed": views_ok, "results": results}
        print(f"{'PASS' if views_ok else 'FAIL'}  view contents ({sum(r['passed'] for r in results)}/{len(results)})")
        for r in results:
            if not r["passed"]:
                print(f"    {r}")
        failed = failed or not views_ok

    # Keyword labels as CATIA Magic's diagram shapes render them
    if args.display and not failed:
        cases = json.loads(DISPLAY_EXPECTED.read_text(encoding="utf-8"))["cases"]
        subjects = sorted({c["subject"] for c in cases})
        (HARNESS_SCRIPTS / "uml3-display-subjects.txt").write_text("\n".join(subjects) + "\n", encoding="utf-8")
        _, disp = call(args.port, "/run-script", {"scriptName": DISPLAY_SCRIPT})
        text = disp.get("result") or disp.get("error") or ""
        (LOGS / "keyword-display.txt").write_text(text, encoding="utf-8")
        labels: dict[str, str] = {}
        for ln in text.splitlines():
            f = ln.split("|")
            if f[0] == "ELEM" and len(f) >= 5 and f[3] == "metadataKeywordsText(true,true)":
                labels[f[1]] = f[4]
            elif f[0] == "ELEM" and len(f) >= 3 and f[2] == "NOT_FOUND":
                labels[f[1]] = "NOT_FOUND"
        results = []
        for c in cases:
            observed_text = labels.get(c["subject"])
            observed = observed_text is not None and observed_text != "NOT_FOUND" and c["contains"] in observed_text
            ok = observed_text not in (None, "NOT_FOUND") and observed == c["expected"]
            results.append({"id": c["id"], "subject": c["subject"], "expected": c["expected"],
                            "observedText": observed_text, "passed": ok})
        disp_ok = bool(results) and all(r["passed"] for r in results)
        report["keywordDisplay"] = {"passed": disp_ok, "results": results}
        print(f"{'PASS' if disp_ok else 'FAIL'}  keyword labels ({sum(r['passed'] for r in results)}/{len(results)})")
        for r in results:
            if not r["passed"]:
                print(f"    {r}")
        failed = failed or not disp_ok

    # Views as diagrams: create, show exposed elements, lay out and export SVG in CATIA Magic (E13, E14), then check
    # display mode, overlaps, drawn shapes and SVG labels; this step undoes its own diagram commands right away
    if args.svg and not failed:
        sys.path.insert(0, str(ROOT / "tools"))
        import check_view_svg as cvs  # noqa: E402
        expectations = [e for e in cvs.load_expectations() if e.get("requires") != "idl" or args.idl]
        svg_dir = LOGS / "svg"
        shutil.rmtree(svg_dir, ignore_errors=True)
        svg_dir.mkdir(parents=True, exist_ok=True)
        (HARNESS_SCRIPTS / "uml3-svg-request.txt").write_text(
            "\n".join(["outDir=" + svg_dir.as_posix()] + ["view=" + e["view"] for e in expectations]) + "\n",
            encoding="utf-8")
        _, ex = call(args.port, "/run-script", {"scriptName": "exportViewDiagrams.groovy"}, timeout=1800)
        text = ex.get("result") or ex.get("error") or ""
        (LOGS / "view-diagrams.txt").write_text(text, encoding="utf-8")
        svg_report = cvs.check(text, expectations)
        (HARNESS_SCRIPTS / "uml3-undo-only.txt").write_text("UML3 View Diagrams\nLayout diagram\n", encoding="utf-8")
        _, undo_diagrams = call(args.port, "/run-script", {"scriptName": UNDO_SCRIPT})
        svg_report["undo"] = undo_diagrams.get("result", undo_diagrams)
        if "undosPerformed=0" in str(svg_report["undo"]) and "TOP|UML3 View Diagrams" in text:
            svg_report["passed"] = False
            svg_report["undoProblem"] = "the view-diagram command was not undone"
        report["viewDiagrams"] = svg_report
        passed_n = sum(r["passed"] for r in svg_report["results"])
        print(f"{'PASS' if svg_report['passed'] else 'FAIL'}  view diagrams / SVG ({passed_n}/{len(svg_report['results'])})")
        for r in svg_report["results"]:
            if not r["passed"]:
                print(f"    {r['view']}: {'; '.join(r['problems'])}")
        failed = failed or not svg_report["passed"]

    # UML3 palettes: what CATIA Magic's model-based customization makes of the UML3 view definitions (E17).
    # Read-only: the DSL service is asked for each view's visualization, palette categories, buttons and the
    # template element (with its UML3 keyword) that each templated button copies.
    if args.palettes and not failed:
        sys.path.insert(0, str(ROOT / "tools"))
        import check_palettes as cpal  # noqa: E402
        spec = json.loads(PALETTE_EXPECTED.read_text(encoding="utf-8"))
        (HARNESS_SCRIPTS / "uml3-palette-request.txt").write_text(
            "\n".join(["resetCache=true", "dialogs=true"] + ["view=" + v["view"] for v in spec["views"]]) + "\n",
            encoding="utf-8")
        _, pv = call(args.port, "/run-script", {"scriptName": "verifyPalettes.groovy"}, timeout=900)
        text = pv.get("result") or pv.get("error") or ""
        (LOGS / "palettes.txt").write_text(text, encoding="utf-8")
        pal_report = cpal.check(text, spec)
        report["palettes"] = pal_report
        passed_n = sum(r["passed"] for r in pal_report["results"])
        print(f"{'PASS' if pal_report['passed'] else 'FAIL'}  UML3 palettes ({passed_n}/{len(pal_report['results'])} views, "
              f"Create View dialog {'ok' if (pal_report['dialog'] or {}).get('passed') else 'not checked/failed'})")
        for r in pal_report["results"]:
            if not r["passed"]:
                print(f"    {r['view']}: {'; '.join(r['problems'])}")
        if pal_report["dialog"] and not pal_report["dialog"]["passed"]:
            print(f"    dialog: {'; '.join(pal_report['dialog']['problems'])}")
        failed = failed or not pal_report["passed"]

        # the diagram-kind model must read back in the tool exactly as the file states it (E18, issue I-35)
        import check_diagram_kinds as cdk  # noqa: E402
        idx = cdk.build_index(Path(ROOT.parent / "SysML-v2-Release" / "sysml.library"))
        model = cdk.parse_kinds(cdk.KINDS, idx)
        (HARNESS_SCRIPTS / "uml3-diagram-kinds-request.txt").write_text("package=UML3DiagramKinds\n", encoding="utf-8")
        _, pk = call(args.port, "/run-script", {"scriptName": "probeDiagramKinds.groovy"}, timeout=900)
        ktext = pk.get("result") or pk.get("error") or ""
        (LOGS / "diagram-kinds.txt").write_text(ktext, encoding="utf-8")
        read: dict[str, dict] = {}
        for ln in ktext.splitlines():
            f = ln.split("|")
            if f[0] == "KIND" and len(f) >= 6:
                read[f[1]] = {"label": f[2], "shows": int(f[3]), "creates": int(f[4]), "views": int(f[5])}
        kind_problems = []
        for name, kind in model.items():
            got = read.get(name)
            if got is None:
                kind_problems.append(f"{name}: CATIA Magic did not report this diagram kind")
                continue
            for role in ("shows", "creates", "views"):
                if got[role] != len(kind[role]):
                    kind_problems.append(f"{name}::{role}: the tool evaluates {got[role]} values, the model lists {len(kind[role])}")
            if kind["label"] and got["label"] != kind["label"]:
                kind_problems.append(f"{name}::label: the tool reads {got['label']!r}, the model says {kind['label']!r}")
        report["diagramKinds"] = {"passed": bool(read) and not kind_problems, "read": read, "problems": kind_problems}
        print(f"{'PASS' if report['diagramKinds']['passed'] else 'FAIL'}  diagram-kind model read back "
              f"({len(read)}/{len(model)} kinds)")
        for kp in kind_problems:
            print(f"    {kp}")
        failed = failed or not report["diagramKinds"]["passed"]

    # Implied-specialization hypotheses (only meaningful when every default file loaded)
    if not failed and not args.files and (not args.library_only or args.hypotheses):
        _, ver = call(args.port, "/run-script", {"scriptName": VERIFY_SCRIPT})
        results, ver_ok = parse_verify(ver.get("result") or ver.get("error") or "")
        report["impliedSpecializations"] = {"passed": ver_ok, "results": results}
        print(f"{'PASS' if ver_ok else 'FAIL'}  implied specializations "
              f"({sum(r.get('status') == 'PASS' for r in results)}/{len(results)} hypotheses)")
        for r in results:
            if r.get("status") != "PASS":
                print(f"    {r}")
        failed = failed or not ver_ok

    if args.palettes:
        # ProjectViewCreationConfig starts with neither UML3 nor OnlineStore, so name it for the guarded undo
        extra = HARNESS_SCRIPTS / "uml3-undo-extra.txt"
        names = extra.read_text(encoding="utf-8").split() if extra.exists() else []
        if "ProjectViewCreationConfig" not in names:
            names.append("ProjectViewCreationConfig")
        extra.write_text("\n".join(names) + "\n", encoding="utf-8")

    if args.undo:
        # When UML3 packages were already loaded before this run (e.g. a model the user is reviewing), undo exactly
        # the commands this run created, so the earlier state survives; otherwise undo until none remain.
        created = sum(1 for l in report["loads"] if l["success"]) + \
            sum(1 for p in report.get("probes", []) if p["observed"] == "OK") + \
            sum(1 for r in report.get("idlRoundTrip", {}).get("results", []) if r["import"].startswith("RESULT|OK"))
        preexisting = "matches=0" not in str(report["inspectBefore"])
        if preexisting:
            (HARNESS_SCRIPTS / "uml3-undo-limit.txt").write_text(str(created), encoding="utf-8")
        _, undo = call(args.port, "/run-script", {"scriptName": UNDO_SCRIPT})
        report["undo"] = undo.get("result", undo)
        report["undoBounded"] = created if preexisting else None
        _, clean = call(args.port, "/run-script", {"scriptName": INSPECT_SCRIPT})
        report["inspectAfterUndo"] = clean.get("result", clean)
        print("UNDO: " + str(report["undo"]).strip().replace("\n", " | "))
        undo_complete = (f"undosPerformed={created} " in str(report["undo"])) if preexisting \
            else ("myPackagesAfter=0" in str(report["undo"]))
        if "STOPPED" in str(report["undo"]) or not undo_complete:
            print("FAIL  undo did not complete safely (foreign command on the undo stack or packages remain) "
                  "- inspect CATIA Magic before continuing")
            failed = True
        print("AFTER UNDO: " + str(report["inspectAfterUndo"]).strip().replace("\n", " | "))

    if args.shutdown:
        _, sd = call(args.port, "/shutdown", {})
        report["shutdown"] = sd

    report["finished"] = dt.datetime.now().isoformat(timespec="seconds")
    report["passed"] = not failed
    (LOGS / "cameo-report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"OVERALL {'PASS' if not failed else 'FAIL'}  (report: {LOGS / 'cameo-report.json'})")
    return 0 if not failed else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        LOGS.mkdir(parents=True, exist_ok=True)
        (LOGS / "cameo-check-error.log").write_text(f"{dt.datetime.now().isoformat()} {exc!r}\n", encoding="utf-8")
        print(f"TOOL ERROR: {exc!r}", file=sys.stderr)
        sys.exit(2)
