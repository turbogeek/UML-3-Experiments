"""
Verify and render the UML 2.x -> UML3 (SysML v2) traceability map.

Source of truth: traceability/uml2-to-uml3.json
Generated doc:   docs/UML2-to-UML3-Traceability.md

Checks (each failure is reported and makes the exit code 1):
  SCHEMA    status is known; PARTIAL/NOT_ADOPTED rows have a rationale; UML3 / NATIVE+UML3 rows cite
            UML3 elements; NATIVE rows cite none (use NATIVE+UML3 instead)
  SYSML     every cited SysML::/KerML:: metaclass exists in the standard library
  UML3      every cited UML3 element exists in library/
  VIEW      every cited view definition exists (StandardViewDefinitions / UML3Views)
  EXAMPLE   every example file exists and contains the quoted snippet
  DOC       the committed Markdown equals the rendering of the JSON (run with --write to regenerate)

Usage: python tools/check_traceability.py --stdlib <sysml.library> [--write] [--report r.json]
Exit code: 0 ok, 1 findings, 2 tool error.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_names as cn  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "traceability" / "uml2-to-uml3.json"
DOC = ROOT / "docs" / "UML2-to-UML3-Traceability.md"
STATUSES = ["NATIVE", "NATIVE+UML3", "UML3", "PARTIAL", "NOT_ADOPTED"]


def build_index(stdlib: str) -> cn.Index:
    idx = cn.Index()
    for f in cn.collect([stdlib], (".sysml", ".kerml")):
        idx.add(cn.index_file(f))
    for f in cn.collect([str(ROOT / "library")], (".sysml",)):
        idx.add(cn.index_file(f))
    idx.finalize()
    return idx


def resolves(idx: cn.Index, qname: str) -> bool:
    if idx.lookup(qname) is not None:
        return True
    root, _, simple = qname.partition("::")
    simple = simple.rpartition("::")[2]
    # KerML / SysML metaclasses live in nested packages (KerML::Kernel::Class, SysML::Systems::...)
    return any(s.name == simple and s.qname.startswith(root + "::") for s in idx._scopes)


def check(data: dict, idx: cn.Index) -> list[dict]:
    findings = []

    def add(code, row, msg):
        findings.append({"code": code, "uml2": row.get("uml2", "?"), "message": msg})

    seen = set()
    for row in data["rows"]:
        key = (row.get("area"), row.get("uml2"))
        if key in seen:
            add("SCHEMA", row, "duplicate row")
        seen.add(key)
        st = row.get("status")
        if st not in STATUSES:
            add("SCHEMA", row, f"unknown status {st!r}")
        if st in ("PARTIAL", "NOT_ADOPTED") and not row.get("rationale"):
            add("SCHEMA", row, f"{st} requires a rationale")
        if st in ("UML3", "NATIVE+UML3") and not row.get("uml3"):
            add("SCHEMA", row, f"{st} requires cited UML3 elements")
        if st == "NATIVE" and row.get("uml3"):
            add("SCHEMA", row, "NATIVE rows must not cite UML3 elements (use NATIVE+UML3)")
        for q in row.get("sysml", []):
            if not resolves(idx, q):
                add("SYSML", row, f"metaclass {q} not found in the standard library")
        for q in row.get("uml3", []):
            if idx.lookup(q) is None:
                add("UML3", row, f"UML3 element {q} not found in library/")
        for q in row.get("views", []):
            if idx.lookup(q) is None:
                add("VIEW", row, f"view definition {q} not found")
        ex = row.get("example")
        if ex:
            path = ROOT / ex["file"]
            if not path.exists():
                add("EXAMPLE", row, f"example file {ex['file']} missing")
            elif not contains_snippet(path.read_text(encoding="utf-8"), ex["contains"]):
                add("EXAMPLE", row, f"snippet not found in {ex['file']}: {ex['contains']!r}")
    return findings


def contains_snippet(text: str, snippet: str) -> bool:
    """The snippet occurs in the model text, ignoring documentation: 'attribute x : T;' matches
    'attribute x : T { doc /* ... */ }' (token streams normalized by compare_model_tokens)."""
    if snippet in text:
        return True
    from compare_model_tokens import normalized  # noqa: E402 (same tools directory)
    whole, part = normalized(text), normalized(snippet)
    # a snippet without a final ';' may be followed by anything, e.g. '#classType item def Customer'
    n = len(part)
    return n > 0 and any(whole[i:i + n] == part for i in range(len(whole) - n + 1))


def cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def code_list(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items) if items else ""


def render(data: dict) -> str:
    rows = data["rows"]
    counts = Counter(r["status"] for r in rows)
    by_area: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_area[r["area"]].append(r)

    out = [f"# {data['title']}", "",
           "<!-- GENERATED by tools/check_traceability.py from traceability/uml2-to-uml3.json. Do not edit by hand. -->",
           "",
           "This document traces each UML 2.x concept to how **UML3** realizes it on SysML v2 and KerML. "
           "UML3 is not a copy of UML 2.x. Where a native SysML v2 element already covers a concept it is **used as-is, without a UML3 label** "
           "(e.g. `action def` for Activity/Behavior), and this map records that decision explicitly. "
           "Every cited metaclass, UML3 element, view definition and example snippet is verified by the test suite.",
           "", "## Status legend", ""]
    for k in STATUSES:
        out.append(f"* **{k}**: {data['statusLegend'][k]}")
    out += ["", "## Summary", "", "| Status | Concepts |", "|---|---|"]
    for k in STATUSES:
        out.append(f"| {k} | {counts.get(k, 0)} |")
    out.append(f"| **Total** | **{len(rows)}** |")
    for area, area_rows in by_area.items():
        out += ["", f"## {area}", "",
                "| UML 2.x | Status | SysML v2 / KerML | UML3 | Notation | Example | Notes |",
                "|---|---|---|---|---|---|---|"]
        for r in area_rows:
            example = ""
            if r.get("example"):
                example = f"[{Path(r['example']['file']).name}](../{r['example']['file']})"
            notes = " ".join(x for x in (r.get("rationale"), r.get("notes")) if x)
            views = code_list(r.get("views", []))
            sysml = code_list(r.get("sysml", [])) + (f"; views: {views}" if views else "")
            out.append("| " + " | ".join([
                cell(r["uml2"]), f"**{r['status']}**", cell(sysml), cell(code_list(r.get("uml3", []))),
                cell(f"`{r['notation']}`" if r.get("notation") else ""), example, cell(notes)]) + " |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdlib", required=True)
    ap.add_argument("--write", action="store_true", help="regenerate docs/UML2-to-UML3-Traceability.md")
    ap.add_argument("--report")
    args = ap.parse_args(argv)

    data = json.loads(MAP.read_text(encoding="utf-8"))
    idx = build_index(args.stdlib)
    if "UML3Core" not in idx.roots or "SysML" not in idx.roots:
        print("TOOL ERROR: index incomplete (UML3Core / SysML missing)", file=sys.stderr)
        return 2
    findings = check(data, idx)
    rendered = render(data)
    if args.write:
        DOC.write_text(rendered, encoding="utf-8")
        print(f"wrote {DOC}")
    elif not DOC.exists() or DOC.read_text(encoding="utf-8") != rendered:
        findings.append({"code": "DOC", "uml2": "-", "message": f"{DOC.name} is out of date; run with --write"})

    for f in findings:
        print(f"{f['code']:<8} {f['uml2']}: {f['message']}")
    counts = Counter(r["status"] for r in data["rows"])
    print("SUMMARY rows=%d %s findings=%d" % (len(data["rows"]), " ".join(f"{k}={counts.get(k, 0)}" for k in STATUSES),
                                               len(findings)))
    if args.report:
        Path(args.report).parent.mkdir(parents=True, exist_ok=True)
        Path(args.report).write_text(json.dumps({"rows": len(data["rows"]), "statusCounts": counts,
                                                 "findings": findings}, indent=2), encoding="utf-8")
    return 1 if findings else 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Exception as exc:
        import traceback
        (ROOT / "logs").mkdir(exist_ok=True)
        (ROOT / "logs" / "check-traceability-error.log").write_text(traceback.format_exc(), encoding="utf-8")
        print(f"TOOL ERROR: {exc!r} (see logs/check-traceability-error.log)", file=sys.stderr)
        sys.exit(2)
